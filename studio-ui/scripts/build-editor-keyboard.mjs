/**
 * Builds the classic-script copies of the code-editor keyboard helpers.
 *
 * Source of truth:
 * - TinyMCE chrome helper: ui/app/src/components/editorKeyboard/tinyMceKeyboard.ts
 * - Ace keyboard helper: ui/app/src/components/editorKeyboard/aceKeyboard.ts
 * - TinyMCE Ace plugin glue: ui/app/src/components/editorKeyboard/tinymceAcePlugin.ignore.js
 *   (the .ignore.js suffix keeps tsconfig.build.json from emitting it)
 * - Hint, frame, focus ring, and target-size CSS: ui/scss/src/_editor-keyboard.scss
 *   (imported by ui/scss/src/tinymce-ace.scss)
 *
 * Outputs (do not edit):
 * - ui/app/src/components/editorKeyboard/editorKeyboardFallbackCss.ts
 * - static-assets/js/editor-keyboard-a11y.js
 * - static-assets/js/tinymce-plugins/ace/plugin.js
 * - static-assets/js/tinymce-plugins/ace/plugin.min.js
 *   (esbuild plugin.js --minify, run in the plugin directory)
 *
 * There is no CI job that diffs plugin.min.js. Run this script after changing
 * the sources above, and commit the outputs.
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const sass = require('sass');
const esbuild = require('esbuild');

const studioUi = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const esbuildBin = path.join(studioUi, 'node_modules/esbuild/bin/esbuild');
const keyboardDir = path.join(studioUi, 'ui/app/src/components/editorKeyboard');
const pluginDir = path.join(studioUi, 'static-assets/js/tinymce-plugins/ace');

const COPYRIGHT = `/*
 * Copyright (C) 2007-2026 Crafter Software Corporation. All Rights Reserved.
 *
 * This program is free software: you can redistribute it and/or modify
 * it under the terms of the GNU General Public License version 3 as published by
 * the Free Software Foundation.
 *
 * This program is distributed in the hope that it will be useful,
 * but WITHOUT ANY WARRANTY; without even the implied warranty of
 * MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the
 * GNU General Public License for more details.
 *
 * You should have received a copy of the GNU General Public License
 * along with this program.  If not, see <http://www.gnu.org/licenses/>.
 */`;

const generatedNote = 'Generated by `yarn build:editor-keyboard`. Do not edit.';

function writeFallbackCss() {
	const compiled = sass.compile(path.join(studioUi, 'ui/scss/src/_editor-keyboard.scss'), {
		style: 'expanded'
	});
	const css = compiled.css.replace(/\s+\n/g, '\n').trim();
	const file = path.join(keyboardDir, 'editorKeyboardFallbackCss.ts');
	const source = `${COPYRIGHT}

// ${generatedNote}
// Source: ui/scss/src/_editor-keyboard.scss
export const EDITOR_KEYBOARD_FALLBACK_CSS = ${JSON.stringify(css)};
`;
	fs.writeFileSync(file, source);
	console.log('wrote', path.relative(studioUi, file));
}

async function bundle(entry, outfile) {
	await esbuild.build({
		entryPoints: [entry],
		bundle: true,
		format: 'iife',
		platform: 'browser',
		target: 'es2022',
		legalComments: 'none',
		banner: { js: `${COPYRIGHT}\n\n/* ${generatedNote} */` },
		outfile
	});
	console.log('bundled', path.relative(studioUi, outfile));
}

function prettier(files) {
	const bin = path.join(studioUi, 'node_modules/prettier/bin/prettier.cjs');
	execFileSync(process.execPath, [bin, '--write', ...files], { cwd: studioUi, stdio: 'inherit' });
}

async function main() {
	writeFallbackCss();
	await bundle(
		path.join(keyboardDir, 'editorKeyboardA11yEntry.ts'),
		path.join(studioUi, 'static-assets/js/editor-keyboard-a11y.js')
	);
	const pluginJs = path.join(pluginDir, 'plugin.js');
	await bundle(path.join(keyboardDir, 'tinymceAcePlugin.ignore.js'), pluginJs);
	prettier([
		path.join(keyboardDir, 'editorKeyboardFallbackCss.ts'),
		path.join(studioUi, 'static-assets/js/editor-keyboard-a11y.js'),
		pluginJs
	]);
	execFileSync(esbuildBin, ['plugin.js', '--minify', '--outfile=plugin.min.js'], {
		cwd: pluginDir,
		stdio: 'inherit'
	});
	console.log('minified plugin.min.js');
}

main().catch((error) => {
	console.error(error);
	process.exit(1);
});
