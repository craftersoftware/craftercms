/** The toast close button is icon-only, so its accessible name has to come from an aria-label (WCAG 4.1.2). */

import '../../../test/stringListDomSetup.mjs';
import '../../../test/registerTsLoader.mjs';
import assert from 'node:assert/strict';
import { afterEach, it } from 'node:test';

Object.defineProperty(globalThis, 'ShadowRoot', { value: window.ShadowRoot, configurable: true, writable: true });

const React = await import('react');
const { act } = await import('react');
const { createRoot } = await import('react-dom/client');
const { RawIntlProvider, createIntl } = await import('react-intl');
const { SnackbarProvider } = await import('notistack');
const { SnackbarCloseButton } = await import('./SnackbarCloseButton.tsx');

const intl = createIntl({ locale: 'en', messages: {}, onError: () => undefined });

const mounted: Array<{ unmount(): void; host: HTMLElement }> = [];
afterEach(async () => {
	await act(async () => {
		for (const { unmount, host } of mounted.splice(0)) {
			unmount();
			host.remove();
		}
	});
});

it('names the close button', async () => {
	const host = document.createElement('div');
	document.body.appendChild(host);
	const root = createRoot(host);
	mounted.push({ unmount: () => root.unmount(), host });
	await act(async () => {
		root.render(
			React.createElement(
				RawIntlProvider,
				{ value: intl },
				React.createElement(SnackbarProvider, null, React.createElement(SnackbarCloseButton, { id: 'toast-1' }))
			)
		);
	});
	const button = host.querySelector('button');
	assert.ok(button, 'the close button did not render');
	assert.equal(button.getAttribute('aria-label'), 'Close');
});
